class student{
    String name;
    int age;
}
class encapsulationEX {
    public static void main(String[] args) {
        student s1=new student();
        s1.name="minal";
        s1.age=20;
        System.out.println("name = "+s1.name);
        System.out.println("age = "+s1.age);
    }
    
}
