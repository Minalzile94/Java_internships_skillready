//syntax of while loop
// while(condition){code}
// here is no initialization and not a increment/decrement
class while_loop {
    public static void main(String[] args) {
      //print the numbers from 1 to 10 using while loop
      int i=1;
      while(i<=10){
        System.out.println(i);
        i++;
      }
    }
}
