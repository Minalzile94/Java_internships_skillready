//print the 1st element and last element in array
// a[]{1}
// a[]={1,2,3,4}
//find the length of array
class First_Last {
    public static void main(String[] args) {
        int[] a={1,2,3,4,5,6,7};
        System.out.println("first element:"+a[0]);
        System.out.println("last element:"+a[6]);
        System.out.println("length of array:"+(a.length/2+1));
        System.out.println("last element:"+a[a.length-1]);
    }
    
}
 